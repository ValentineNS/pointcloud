import Foundation
import simd

/// Запись облака точек в формат PLY (binary_little_endian или ascii).
enum PLYWriter {
    static func write(_ points: [SIMD3<Float>], to url: URL, binary: Bool = true) throws {
        var data = Data()
        let fmt = binary ? "binary_little_endian" : "ascii"
        let header = """
        ply
        format \(fmt) 1.0
        comment Generated by PointCloud app (ARKit rawFeaturePoints)
        element vertex \(points.count)
        property float x
        property float y
        property float z
        end_header

        """
        data.append(header.data(using: .ascii)!)

        if binary {
            var body = Data(capacity: points.count * 12)
            for p in points {
                var x = p.x.bitPattern.littleEndian
                var y = p.y.bitPattern.littleEndian
                var z = p.z.bitPattern.littleEndian
                withUnsafeBytes(of: &x) { body.append(contentsOf: $0) }
                withUnsafeBytes(of: &y) { body.append(contentsOf: $0) }
                withUnsafeBytes(of: &z) { body.append(contentsOf: $0) }
            }
            data.append(body)
        } else {
            var s = ""
            s.reserveCapacity(points.count * 40)
            for p in points {
                s += "\(p.x) \(p.y) \(p.z)\n"
            }
            data.append(s.data(using: .ascii)!)
        }

        try data.write(to: url)
    }
}
